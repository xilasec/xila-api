package sbom

import (
	"cmp"
	"fmt"
	"maps"
	"slices"
	"strings"
	"time"

	"github.com/gofiber/fiber/v2"

	"github.com/xilasec/xila-api/internal/export"
)

// Notices handles GET /projects/{id}/notices: a third-party notices file
// (Markdown) for the components of the latest SBOM of each artifact, with
// each one's license, copyright and homepage, and what its licenses require.
// It reads the same component query as the component list and export
// (?latest is forced on), so it can't name a component the list hides.
func (h *Handler) Notices(c *fiber.Ctx) error {
	f, err := h.projectComponentFilter(c)
	if err != nil {
		return err
	}
	f.LatestOnly = true
	var comps []ComponentHit
	truncated := false
	err = h.repo.EachComponent(c.UserContext(), f, export.MaxRows+1, func(hit ComponentHit) error {
		if len(comps) == export.MaxRows {
			truncated = true
			return nil
		}
		comps = append(comps, hit)
		return nil
	})
	if err != nil {
		return err
	}
	conditions := h.conditions
	if conditions == nil {
		conditions = func(string) []string { return nil }
	}
	c.Set(fiber.HeaderContentType, "text/markdown; charset=utf-8")
	c.Set(fiber.HeaderContentDisposition, `attachment; filename="THIRD-PARTY-NOTICES.md"`)
	return c.SendString(RenderNotices(comps, conditions, time.Now(), truncated))
}

// noticeEntry is one distinct component of a notices file.
type noticeEntry struct {
	name, version, purl, license, copyright, homepage string
}

// RenderNotices lays out a notices file: the distinct components (the same
// package in several artifacts is listed once, with every copyright and
// homepage its SBOMs state), sorted by name, then each license id's
// conditions. A component with no stated license or copyright says so rather
// than being left out: a gap in the evidence is part of the answer.
func RenderNotices(comps []ComponentHit, conditions func(id string) []string, now time.Time, truncated bool) string {
	byKey := map[string]*noticeEntry{}
	var order []string
	licenseIDs := map[string]bool{}
	for _, h := range comps {
		if h.Kind == KindAIService {
			continue // derived from a service, not a shipped component
		}
		key := cmp.Or(h.Purl, h.Group+"/"+h.Name+"@"+h.Version)
		e, ok := byKey[key]
		if !ok {
			name := h.Name
			if h.Group != "" {
				name = h.Group + "/" + h.Name
			}
			e = &noticeEntry{name: name, version: h.Version, purl: h.Purl}
			byKey[key] = e
			order = append(order, key)
		}
		e.license = cmp.Or(e.license, h.LicenseExpression, h.License)
		e.copyright = joinDistinct(e.copyright, h.Copyright)
		e.homepage = cmp.Or(e.homepage, h.Homepage)
		for _, id := range h.LicenseIDs {
			licenseIDs[id] = true
		}
	}
	slices.SortFunc(order, func(a, b string) int {
		return cmp.Or(strings.Compare(strings.ToLower(byKey[a].name), strings.ToLower(byKey[b].name)),
			strings.Compare(byKey[a].version, byKey[b].version), strings.Compare(a, b))
	})

	var b strings.Builder
	b.WriteString("# Third-party notices\n\n")
	fmt.Fprintf(&b, "%d components, from the latest SBOM of each artifact. Generated by Xila on %s.\n",
		len(order), now.UTC().Format(time.DateOnly))
	if truncated {
		fmt.Fprintf(&b, "\nOnly the first %d components are listed: narrow the export to see the rest.\n", export.MaxRows)
	}
	for _, key := range order {
		e := byKey[key]
		fmt.Fprintf(&b, "\n## %s %s\n\n", e.name, e.version)
		if e.purl != "" {
			fmt.Fprintf(&b, "- Package: `%s`\n", e.purl)
		}
		fmt.Fprintf(&b, "- License: %s\n", cmp.Or(e.license, "not stated"))
		fmt.Fprintf(&b, "- Copyright: %s\n", cmp.Or(e.copyright, "not stated"))
		if e.homepage != "" {
			fmt.Fprintf(&b, "- Homepage: <%s>\n", e.homepage)
		}
	}
	var lines []string
	for _, id := range slices.Sorted(maps.Keys(licenseIDs)) {
		if conds := conditions(id); len(conds) > 0 {
			lines = append(lines, fmt.Sprintf("- %s: %s", id, strings.Join(conds, ", ")))
		}
	}
	if len(lines) > 0 {
		b.WriteString("\n## What these licenses require\n\n")
		b.WriteString("Conditions from choosealicense.com (for example, include-copyright: ship the copyright notice).\n\n")
		b.WriteString(strings.Join(lines, "\n") + "\n")
	}
	return b.String()
}

// joinDistinct adds s to a "; "-separated list unless it's empty or present.
func joinDistinct(list, s string) string {
	switch {
	case s == "":
		return list
	case list == "":
		return s
	case slices.Contains(strings.Split(list, "; "), s):
		return list
	}
	return list + "; " + s
}
