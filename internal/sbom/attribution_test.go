// Every SBOM format's copyright and homepage reach the component; "not
// stated" markers and non-http(s) URLs don't.
func TestParseAttribution(t *testing.T) {
	docs := map[string]string{
		"cyclonedx json": `{"bomFormat":"CycloneDX","specVersion":"1.6","components":[
			{"type":"library","name":"express","version":"4.17.1","copyright":"Copyright (c) 2009-2014  TJ Holowaychuk",
			 "externalReferences":[{"type":"vcs","url":"https://github.com/expressjs/express"},{"type":"website","url":"https://expressjs.com/"}]}]}`,
		"cyclonedx xml": `<?xml version="1.0"?><bom xmlns="http://cyclonedx.org/schema/bom/1.6" version="1"><components>
			<component type="library"><name>express</name><version>4.17.1</version>
			<copyright> Copyright (c) 2009-2014 TJ Holowaychuk </copyright>
			<externalReferences><reference type="website"><url>https://expressjs.com/</url></reference></externalReferences>
			</component></components></bom>`,
		"spdx": `{"spdxVersion":"SPDX-2.3","SPDXID":"SPDXRef-DOCUMENT","packages":[
			{"SPDXID":"SPDXRef-express","name":"express","versionInfo":"4.17.1","copyrightText":"Copyright (c) 2009-2014 TJ Holowaychuk",
			 "homepage":"https://expressjs.com/"}]}`,
		"scancode.io": `{"headers":[{"tool_name":"scanpipe"}],"packages":[
			{"type":"npm","name":"express","version":"4.17.1","purl":"pkg:npm/express@4.17.1",
			 "copyright":"Copyright (c) 2009-2014 TJ Holowaychuk","homepage_url":"https://expressjs.com/"}],"dependencies":[]}`,
	}
	for name, raw := range docs {
		doc, err := Parse([]byte(raw))
		if err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		var c *Component
		for i := range doc.Components {
			if doc.Components[i].Name == "express" {
				c = &doc.Components[i]
			}
		}
		if c == nil || c.Copyright != "Copyright (c) 2009-2014 TJ Holowaychuk" || c.Homepage != "https://expressjs.com/" {
			t.Errorf("%s: express = %+v", name, c)
		}
	}

	for _, tc := range []struct{ in, want string }{
		{"NOASSERTION", ""}, {"NONE", ""}, {"  a\n b ", "a b"},
		{strings.Repeat("x", maxCopyright+5), strings.Repeat("x", maxCopyright)},
	} {
		if got := cleanCopyright(tc.in); got != tc.want {
			t.Errorf("cleanCopyright(%.20q) = %.20q, want %.20q", tc.in, got, tc.want)
		}
	}
	for in, want := range map[string]string{
		"https://lodash.com/": "https://lodash.com/", "http://x.example": "http://x.example",
		"javascript:alert(1)": "", "NOASSERTION": "", "//lodash.com": "", "ftp://x.example": "",
	} {
		if got := cleanHomepage(in); got != want {
			t.Errorf("cleanHomepage(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestRenderNotices(t *testing.T) {
	hit := func(name, version, purl, lic, copyright, homepage string, ids ...string) ComponentHit {
		h := ComponentHit{}
		h.Name, h.Version, h.Purl, h.LicenseExpression, h.Copyright, h.Homepage, h.LicenseIDs = name, version, purl, lic, copyright, homepage, ids
		return h
	}
	comps := []ComponentHit{
		hit("lodash", "4.17.21", "pkg:npm/lodash@4.17.21", "MIT", "Copyright OpenJS Foundation", "https://lodash.com/", "MIT"),
		// The same package in a second artifact, stating another notice: listed once, both notices kept.
		hit("lodash", "4.17.21", "pkg:npm/lodash@4.17.21", "MIT", "Copyright Jeremy Ashkenas", "", "MIT"),
		hit("Zlib-thing", "1.0", "", "", "", ""),
		hit("gpl-lib", "2.0", "pkg:npm/gpl-lib@2.0", "GPL-3.0-only", "Copyright Someone", "", "GPL-3.0-only"),
	}
	conditions := func(id string) []string {
		return map[string][]string{"MIT": {"include-copyright"}, "GPL-3.0-only": {"include-copyright", "disclose-source"}}[id]
	}
	out := RenderNotices(comps, conditions, time.Date(2026, 11, 28, 0, 0, 0, 0, time.UTC), false)
	for _, want := range []string{
		"3 components", "Generated by Xila on 2026-11-28",
		"## gpl-lib 2.0", "## lodash 4.17.21",
		"- Copyright: Copyright OpenJS Foundation; Copyright Jeremy Ashkenas",
		"- Homepage: <https://lodash.com/>",
		"## Zlib-thing 1.0\n\n- License: not stated\n- Copyright: not stated",
		"- GPL-3.0-only: include-copyright, disclose-source", "- MIT: include-copyright",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("notices lack %q:\n%s", want, out)
		}
	}
	if strings.Index(out, "## gpl-lib") > strings.Index(out, "## lodash") || strings.Count(out, "## lodash") != 1 {
		t.Errorf("components not listed once each, sorted by name:\n%s", out)
	}
	if !strings.Contains(RenderNotices(nil, conditions, time.Now(), true), "Only the first") {
		t.Error("a truncated file doesn't say so")
	}
}

func TestOriginalFilename(t *testing.T) {
	for _, tc := range []struct {
		s    Sbom
		want string
	}{
		{Sbom{Artifact: "my app", Version: "1.2.0", OriginalMediaType: "application/vnd.cyclonedx+json"}, "my-app-1.2.0.cdx.json"},
		{Sbom{Artifact: `x"; rm -rf /`, OriginalMediaType: "application/spdx+json"}, "x__-rm--rf-_.spdx.json"},
		{Sbom{ID: "abc", OriginalMediaType: "application/vnd.cyclonedx+xml"}, "sbom-abc.cdx.xml"},
	} {
		if got := originalFilename(tc.s); got != tc.want {
			t.Errorf("originalFilename(%q) = %q, want %q", tc.s.Artifact, got, tc.want)
		}
	}
}
